#!/bin/bash
# QED Dataset Experiments: Train and evaluate OPT-350m and Pythia-410m
# students distilled from Llama-2-7b-chat-hf, Qwen2-8B, or BLOOMZ-560M
#
# Usage:
#   bash run_experiments_qed.sh <teacher_model_path> <student_model> <seed> [span_kd_enabled]
#
# Example:
#   bash run_experiments_qed.sh /workspace/models/Llama-2-7b-chat-hf opt-350m 42 true
#   bash run_experiments_qed.sh /workspace/models/Qwen2-8B pythia-410m 4 false
#   bash run_experiments_qed.sh /workspace/models/bloomz-560M opt-350m 42 true
#   bash run_experiments_qed.sh /workspace/models/Llama-2-7b-chat-hf opt-350m 42 random   # random-span control
#   bash run_experiments_qed.sh /workspace/models/Llama-2-7b-chat-hf opt-350m 42 matched  # matched-weight control
#
# Optional env:
#   SPAN_TOP_R_EXTRA="1.0"  extra r points trained alongside the sweep (analysis only,
#                           never used for dev winner selection)
#   MAX_SAMPLES=16          DRY RUN: 16 rows of train/dev/dev-gen, 1 epoch, run tag gets _dryrun
#   SKIP_EVAL=1             skip the two test-set evaluation steps
#   LOW_DELTA=0.25          span_low_delta for the span arms (default 0.1). A non-default
#                           value adds _d<delta> to the run tag so it never overwrites
#                           the main runs. delta=1 is vanilla MLOT: run arm 'false' instead.

set -euo pipefail

if [ $# -lt 3 ]; then
  echo "Usage: bash run_experiments_qed.sh <teacher_model_path> <student_model> <seed> [span_kd_enabled]" >&2
  echo "" >&2
  echo "Arguments:" >&2
  echo "  teacher_model_path  : Path to teacher model (e.g., /workspace/models/Llama-2-7b-chat-hf)" >&2
  echo "  student_model       : opt-350m or pythia-410m" >&2
  echo "  seed                : Random seed for reproducibility" >&2
  echo "  span_kd_enabled     : true|false|random|matched (default: true)" >&2
  echo "                        true=SpanOT-KD, false=vanilla MLOT, random=random-span control," >&2
  echo "                        matched=same per-sample mean weight as SpanOT-KD, uniform positions" >&2
  exit 1
fi
SPAN_TOP_R_EXTRA="${SPAN_TOP_R_EXTRA:-}"
MAX_SAMPLES="${MAX_SAMPLES:-0}"
SKIP_EVAL="${SKIP_EVAL:-0}"
LOW_DELTA="${LOW_DELTA:-0.1}"

export HOME=${HOME:-/workspace}
TEACHER_MODEL_PATH="$1"
STUDENT_MODEL="$2"
SEED="$3"
SPAN_KD_ENABLED="${4:-true}"
FIXED_R="${5:-}"   # optional: fixed span_top_r (no sweep). Empty = sweep {0.3,0.5,0.7} with dev selection.

# Validate inputs
if [ ! -d "$TEACHER_MODEL_PATH" ]; then
  echo "ERROR: Teacher model path does not exist: $TEACHER_MODEL_PATH" >&2
  exit 1
fi

case "$STUDENT_MODEL" in
  opt-350m|pythia-410m)
    ;;
  *)
    echo "ERROR: Invalid student model. Must be 'opt-350m' or 'pythia-410m'" >&2
    exit 1
    ;;
esac

REPO_PATH="$HOME/SpanOT-KD"
STUDENT_PATH="$REPO_PATH/EleutherAI/$STUDENT_MODEL"
DATASET_FILE="$REPO_PATH/llm_distillation/datasets/loader/qed.py"
# Previously OUTPUT_DIR/eval paths only encoded the student name+seed, so
# every teacher x {vanilla,SpanOT-KD} combination at the same student+seed
# silently overwrote each other's checkpoints AND eval predictions. Encode
# teacher basename + method so runs are distinguishable on disk.
TEACHER_TAG="$(basename "$TEACHER_MODEL_PATH")"
case "$SPAN_KD_ENABLED" in
  true)   METHOD_TAG="spanotkd" ;;
  random) METHOD_TAG="randomspan" ;;   # random-span control, same r sweep + dev selection as SpanOT-KD
  matched) METHOD_TAG="matchedweight" ;;  # matched-weight control, same r sweep + dev selection as SpanOT-KD
  false)  METHOD_TAG="vanilla" ;;
  scaled)  # WP8 global-scalar control: vanilla MLOT with distil_factor = 0.15 * w_eff(r).
           # Commands are generated by scripts/make_scaled_commands.py.
    if [ -z "${DISTIL_FACTOR:-}" ] || [ -z "${SCALED_R:-}" ]; then
      echo "ERROR: arm 'scaled' needs DISTIL_FACTOR and SCALED_R env vars" >&2; exit 1
    fi
    METHOD_TAG="mlotscaled_r${SCALED_R}" ;;
  *) echo "ERROR: span_kd_enabled must be true|false|random|matched|scaled, got '$SPAN_KD_ENABLED'" >&2; exit 1 ;;
esac
if [ "$SPAN_KD_ENABLED" != "scaled" ] && [ -n "${DISTIL_FACTOR:-}" ] && [ "$DISTIL_FACTOR" != "0.15" ]; then
  echo "ERROR: DISTIL_FACTOR override is only allowed for arm 'scaled'" >&2; exit 1
fi
DISTIL_FACTOR="${DISTIL_FACTOR:-0.15}"
if ! awk -v d="$LOW_DELTA" 'BEGIN { exit !(d ~ /^[0-9]*\.?[0-9]+$/ && d >= 0 && d < 1) }'; then
  echo "ERROR: LOW_DELTA must be a number in [0, 1), got '$LOW_DELTA' (delta=1 is vanilla: use arm 'false')" >&2; exit 1
fi
if [ "$LOW_DELTA" != "0.1" ]; then
  case "$SPAN_KD_ENABLED" in
    true|random|matched) METHOD_TAG="${METHOD_TAG}_d${LOW_DELTA}" ;;
    *) echo "ERROR: LOW_DELTA override only applies to span arms (true|random|matched)" >&2; exit 1 ;;
  esac
fi
if [ -n "$FIXED_R" ]; then METHOD_TAG="${METHOD_TAG}_r${FIXED_R}"; fi
RUN_TAG="${STUDENT_MODEL%%-*}_${TEACHER_TAG}_${METHOD_TAG}_seed${SEED}"
if [ "$MAX_SAMPLES" != "0" ]; then RUN_TAG="${RUN_TAG}_dryrun"; fi
OUTPUT_DIR="$REPO_PATH/output_qed_${RUN_TAG}"

echo "════════════════════════════════════════════════════════════════"
echo "QED Dataset Experiments"
echo "════════════════════════════════════════════════════════════════"
echo "Teacher Model    : $TEACHER_MODEL_PATH"
echo "Student Model    : $STUDENT_MODEL"
echo "Student Path     : $STUDENT_PATH"
echo "Seed             : $SEED"
echo "SpanOT-KD        : $SPAN_KD_ENABLED"
echo "span_low_delta   : $LOW_DELTA (ignored unless span arm)"
echo "Dataset          : QED"
echo "Output Dir       : $OUTPUT_DIR"
echo "════════════════════════════════════════════════════════════════"
echo ""

# Build training command
TRAIN_CMD="python $REPO_PATH/finetuning.py \
  --model_name $STUDENT_PATH \
  --dataset.file $DATASET_FILE \
  --lr 1e-6 \
  --num_epochs 5 \
  --batch_size_training 2 \
  --gradient_accumulation_steps 1 \
  --val_batch_size 1 \
  --output_dir $OUTPUT_DIR \
  --distillation_config_model_name $TEACHER_MODEL_PATH \
  --distillation \
  --distillation_config_pure_bf16 \
  --distillation_config_distil_factor $DISTIL_FACTOR \
  --dev_split_ratio 0.1 \
  --dev_split_seed $SEED \
  --early_stopping_patience 3 \
  --dev_gen_batch_size 1 \
  --f 1 \
  --seed $SEED"

if [ "$SPAN_KD_ENABLED" = "true" ] || [ "$SPAN_KD_ENABLED" = "random" ] || [ "$SPAN_KD_ENABLED" = "matched" ]; then
  TRAIN_CMD="$TRAIN_CMD \
  --distillation_config_span_kd_enabled \
  --distillation_config_span_aggregation mean \
  --distillation_config_span_low_delta $LOW_DELTA"
  if [ -n "$FIXED_R" ]; then
    TRAIN_CMD="$TRAIN_CMD --distillation_config_span_top_r $FIXED_R"
  else
    TRAIN_CMD="$TRAIN_CMD --distillation_config_span_top_r_sweep"
    if [ -n "$SPAN_TOP_R_EXTRA" ]; then
      TRAIN_CMD="$TRAIN_CMD --distillation_config_span_top_r_extra $SPAN_TOP_R_EXTRA"
    fi
  fi
fi
if [ "$SPAN_KD_ENABLED" = "random" ]; then
  TRAIN_CMD="$TRAIN_CMD \
  --distillation_config_span_select_mode random \
  --distillation_config_span_random_pool active"
fi
if [ "$SPAN_KD_ENABLED" = "matched" ]; then
  TRAIN_CMD="$TRAIN_CMD \
  --distillation_config_span_select_mode matched"
fi
if [ "$MAX_SAMPLES" != "0" ]; then
  # Later --num_epochs overrides the earlier one (argparse keeps the last).
  TRAIN_CMD="$TRAIN_CMD --max_samples $MAX_SAMPLES --num_epochs 1"
fi

echo "[1/3] Training..."
CUDA_VISIBLE_DEVICES=0 PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True eval "$TRAIN_CMD"
echo "$TRAIN_CMD" > "$OUTPUT_DIR/train_cmd.txt"

if [ "$SKIP_EVAL" = "1" ]; then
  echo "SKIP_EVAL=1 — skipping test-set evaluation."
  exit 0
fi

# benchmarkqedllama.py writes <output_path>/0shots.json without creating the
# directory, so a fresh RUN_TAG would crash after the full test-set generation.
mkdir -p "$REPO_PATH/eval_results/qed_${RUN_TAG}" "$REPO_PATH/eval_results/qed_${RUN_TAG}_loss"

echo ""
echo "[2/3] Evaluating (best_dev_f1 checkpoint)..."
EVAL_CMD_F1="python $REPO_PATH/llm_distillation/benchmark/benchmarkqedllama.py \
  --model_id $OUTPUT_DIR/best_dev_f1 \
  --model_tokenizer $STUDENT_PATH \
  --dataset_id $REPO_PATH/llm_distillation/datasets/processed/qed \
  --split_name validation \
  --batch_size 4 \
  --num_workers 2 \
  --context_length 1024 \
  --from_disk \
  --task qa \
  --bfloat \
  --save_predictions \
  --output_path $REPO_PATH/eval_results/qed_${RUN_TAG}/"

CUDA_VISIBLE_DEVICES=0 eval "$EVAL_CMD_F1"

echo ""
echo "[3/3] Evaluating (best_dev_loss checkpoint)..."
EVAL_CMD_LOSS="python $REPO_PATH/llm_distillation/benchmark/benchmarkqedllama.py \
  --model_id $OUTPUT_DIR/best_dev_loss \
  --model_tokenizer $STUDENT_PATH \
  --dataset_id $REPO_PATH/llm_distillation/datasets/processed/qed \
  --split_name validation \
  --batch_size 4 \
  --num_workers 2 \
  --context_length 1024 \
  --from_disk \
  --task qa \
  --bfloat \
  --save_predictions \
  --output_path $REPO_PATH/eval_results/qed_${RUN_TAG}_loss/"

CUDA_VISIBLE_DEVICES=0 eval "$EVAL_CMD_LOSS"

echo ""
echo "════════════════════════════════════════════════════════════════"
echo "QED Experiments Complete"
echo "Results saved to:"
echo "  - $REPO_PATH/eval_results/qed_${RUN_TAG}/"
echo "  - $REPO_PATH/eval_results/qed_${RUN_TAG}_loss/"
echo "════════════════════════════════════════════════════════════════"
